"""Generate finite addon release workflows with authentication-scoped permissions."""
import argparse
from pathlib import Path

import workflow_bootstrap


ROOT = Path(__file__).resolve().parents[1]
AUTHENTICATIONS = {'api-key': 'apikey', 'oidc': 'oidc'}


def workflow_path(authentication):
    return '.github/workflows/cookbook-addon-release-' + AUTHENTICATIONS[authentication] + '.yml'


def _render(text, values):
    for key, value in values.items():
        text = text.replace('@@' + key + '@@', value)
    if '@@' in text:
        raise ValueError('unresolved addon release workflow template field')
    return text


def workflow_files():
    prefix, publisher = (ROOT / 'cookbook/addon_release.yml.in').read_text().split('@@PUBLISHER@@\n')
    result = {}
    for authentication in AUTHENTICATIONS:
        common = {'AUTH': authentication, 'PRIVATE_STEPS': workflow_bootstrap.private_steps(indent=6)}
        api_key = authentication == 'api-key'
        secrets = '    secrets:\n      gdam-key:\n        required: true\n' if api_key else ''
        workflow = '# Generated by cookbook/addon_release_workflows.py.\n' + _render(prefix, common | {'SECRETS': secrets})
        for environment in [False, True]:
            workflow += '  publish' + ('-environment' if environment else '') + ':\n'
            workflow += _render(publisher, common | {
                'ENV_CONDITION': '!=' if environment else '==',
                'TOKEN_PERMISSION': '' if api_key else '      id-token: write\n',
                'ENVIRONMENT': '    environment: ${{ needs.plan.outputs.environment }}\n' if environment else '',
                'REGISTRY_KEY': '          api-key: ${{ secrets.gdam-key }}\n' if api_key else '',
            })
        result[workflow_path(authentication)] = workflow
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, expected in workflow_files().items():
        path = ROOT / name
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                raise SystemExit('addon release workflow differs from its canonical source: ' + name)
        else:
            path.write_text(expected)


if __name__ == '__main__':
    main()
