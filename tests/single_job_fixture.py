#!/usr/bin/env python3
"""Write a complete, committed minimal source for one-job validation rehearsals: a Godot addon or a Rust CLI.

Usage: single_job_fixture.py DESTINATION COOKBOOK_REVISION [addon|rust-cli]
Needs TOOLS_ROOT to name the separate pinned Tools checkout. Prints the fixture commit.
"""
import hashlib
from pathlib import Path
import subprocess
import sys

COOKBOOK = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(COOKBOOK / 'cookbook'))
import dependencies
import generate

# The exact official Godot 4.7.2 archives that the host setup always prepares.
GODOT = {
    'GODOT_VERSION': '4.7.2',
    'GODOT_EXPECTED_VERSION': '4.7.2.stable.official.ed1daf0bf',
    'GODOT_BINARY_CHECKSUM': 'sha256:cadd3204e728a35d3f13adb7fd0d7902636b79f6b95c40c265eb73b6c35329e4',
    'GODOT_TEMPLATES_CHECKSUM': 'sha512:ca4d71c4d7b81dfc15d1a98baa07534aa95b03fdda78a0075b06672e1648d2e5f40980c9adc28d23e1b92e732ee7bf3461997aa804af74ec2fcd7a93ccb84079',
}
README = '# Fixture\nNative single-job validation fixture.\n'

# The Rust CLI fixture declares these platforms; one job validates each of them.
PLATFORMS = [('Linux', 'x86_64', 'ubuntu-24.04', 'x86_64-unknown-linux-musl', 'tar.gz'),
             ('Linux', 'arm64', 'ubuntu-24.04-arm', 'aarch64-unknown-linux-musl', 'tar.gz'),
             ('Darwin', 'arm64', 'macos-15', 'aarch64-apple-darwin', 'tar.gz')]
CARGO_MANIFEST = '[package]\nname = "example"\nversion = "0.0.1"\nedition = "2021"\n'
CARGO_LOCK = ('# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\n'
              'version = 4\n\n[[package]]\nname = "example"\nversion = "0.0.1"\n')
MAIN = ('fn main() {\n    println!("example dev");\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n'
        '    fn arithmetic() {\n        assert_eq!(2 + 2, 4);\n    }\n}\n')
TARGET = '''[[package.native_targets]]
platform="{0}"
arch="{1}"
runner="{2}"
target="{3}"
extension="{4}"
checks=["tests/test_behavior.py"]
'''
RUST_CLI = '''version=1
recipe="rust-cli"
[ci]
single_job=true
[[components.rust]]
name="cli"
manifest="Cargo.toml"
binaries=["example"]
[package]
binary="example"
files=["README.md"]
version_arguments=["--version"]
version_template="{{binary}} {{version}}"
{targets}[[tests.integration]]
runner="python"
path="tests/test_behavior.py"
[clean]
paths=["dist", ".artifacts/build", ".artifacts/native-package"]
'''


def addon(root):
    (root / 'addon').mkdir()
    (root / 'addon/plugin.cfg').write_text('[plugin]\nversion="0.0.1"\n')
    (root / 'package.files').write_text('plugin.cfg\n')
    (root / '.gitignore').write_text('/.artifacts/\n/dist/\n')
    (root / 'cookbook.toml').write_text('''version=1
recipe="godot-addon"
[package]
archive="dist/@owner_addon.zip"
[clean]
paths=["dist"]
[[tests.unit]]
runner="python"
path="tests/test_behavior.py"
[[tests.integration]]
runner="python"
path="tests/test_behavior.py"
''')
    (root / 'mise.toml').write_text('[tools]\npython="3.13.11"\nactionlint="1.7.12"\n[env]\n'
                                    + ''.join(key + '="' + value + '"\n' for key, value in GODOT.items()))


def rust_cli(root):
    (root / 'src').mkdir()
    (root / 'Cargo.toml').write_text(CARGO_MANIFEST)
    (root / 'Cargo.lock').write_text(CARGO_LOCK)
    (root / 'src/main.rs').write_text(MAIN)
    (root / '.gitignore').write_text('/.artifacts/\n/dist/\n/target/\n')
    (root / 'cookbook.toml').write_text(RUST_CLI.format(targets=''.join(TARGET.format(*row) for row in PLATFORMS)))
    (root / 'mise.toml').write_text('[tools]\npython="3.13.11"\nrust="1.94.0"\nactionlint="1.7.12"\n')


def write(root, revision, kind='addon'):
    root = Path(root)
    (root / 'tests').mkdir(parents=True)
    (root / '.github').mkdir()
    (root / 'README.md').write_text(README)
    dependencies.helper('source_config').write(root / '.github/readme-source.toml', {
        'version': 1, 'sha256': hashlib.sha256(README.encode()).hexdigest()})
    (root / 'tests/test_behavior.py').write_text('assert 2 + 2 == 4\n')
    {'addon': addon, 'rust-cli': rust_cli}[kind](root)
    files = {**generate.entrypoint_files(root, revision), **generate.workflow_files(root, revision)}
    for name, body in files.items():
        path = root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(body.encode('utf-8'))
    for argv in [['init', '-q', '-b', 'main'], ['add', '.'],
                 ['-c', 'user.name=Recipe Controls', '-c', 'user.email=recipe@example.invalid',
                  'commit', '-qm', 'single-job fixture']]:
        subprocess.run(['git', '-C', str(root), *argv], check=True)
    return subprocess.check_output(['git', '-C', str(root), 'rev-parse', 'HEAD'], text=True).strip()


if __name__ == '__main__':
    destination, revision, *kind = sys.argv[1:]
    print(write(destination, revision, *kind))
